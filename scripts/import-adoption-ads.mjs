import { createHash } from "node:crypto";
import { spawnSync, execFileSync } from "node:child_process";
import { basename, resolve } from "node:path";
import {
  readFileSync,
  writeFileSync,
  copyFileSync,
  existsSync,
  mkdirSync,
} from "node:fs";

const args = process.argv.slice(2);
const option = (name) => args[args.indexOf(name) + 1];
if (!args.includes("--girl"))
  throw new Error(
    "Usage: node scripts/import-adoption-ads.mjs --girl <video> [--ffmpeg <executable>]",
  );
const ffmpeg = args.includes("--ffmpeg") ? option("--ffmpeg") : "ffmpeg";
const inputs = [
  {
    id: "adoption-girl-in-the-middle",
    title: "The Girl in the Middle",
    source: option("--girl"),
    slug: "the-girl-in-the-middle",
    caption:
      "A 60-second adoption awareness film. Help this story reach more people and support adoption awareness.",
  },
];
mkdirSync("public/videos/adoption", { recursive: true });
mkdirSync("public/images/adoption", { recursive: true });
const ads = inputs.map(({ source, slug, ...ad }) => {
  const bytes = readFileSync(resolve(source));
  if (!bytes.length || bytes.length > 30 * 1024 * 1024)
    throw new Error(`${ad.title} must fit the demo's 30 MB limit.`);
  const probe = spawnSync(ffmpeg, ["-hide_banner", "-i", resolve(source)], {
    encoding: "utf8",
  });
  const metadata = probe.stderr || "";
  const duration = /Duration: (\d+):(\d+):(\d+\.\d+)/.exec(metadata);
  if (!duration || !metadata.includes("Video:") || !metadata.includes("Audio:"))
    throw new Error(`${ad.title} needs a readable video and audio track.`);
  const durationSeconds =
    Number(duration[1]) * 3600 + Number(duration[2]) * 60 + Number(duration[3]);
  if (durationSeconds < 59 || durationSeconds > 62)
    throw new Error(`${ad.title} is not the expected 60-second film.`);
  execFileSync(
    ffmpeg,
    [
      "-hide_banner",
      "-loglevel",
      "error",
      "-xerror",
      "-i",
      resolve(source),
      "-map",
      "0:v:0",
      "-map",
      "0:a:0",
      "-f",
      "null",
      "-",
    ],
    { stdio: "pipe" },
  );
  const digest = createHash("sha256").update(bytes).digest("hex");
  const media = `/videos/adoption/${slug}.mp4`;
  const poster = `/images/adoption/${slug}.jpg`;
  const output = `public${media}`;
  if (
    existsSync(output) &&
    createHash("sha256").update(readFileSync(output)).digest("hex") !== digest
  )
    throw new Error(
      `Preserve the existing ${output}; use a new asset version for a different film.`,
    );
  copyFileSync(resolve(source), output);
  execFileSync(
    ffmpeg,
    [
      "-hide_banner",
      "-loglevel",
      "error",
      "-ss",
      "15",
      "-i",
      output,
      "-frames:v",
      "1",
      "-vf",
      "scale=1280:-1",
      "-y",
      `public${poster}`,
    ],
    { stdio: "pipe" },
  );
  return {
    ...ad,
    media,
    poster,
    durationSeconds,
    bytes: bytes.length,
    digest,
    sourceFilename: basename(source),
  };
});
writeFileSync(
  "src/public-demo/adoption-ads.js",
  `// Generated by scripts/import-adoption-ads.mjs from the supplied full-length videos.\nexport const adoptionAds = ${JSON.stringify(ads, null, 2)};\n`,
);
console.log(
  ads.map(({ title, bytes, durationSeconds }) => ({
    title,
    bytes,
    durationSeconds,
  })),
);
